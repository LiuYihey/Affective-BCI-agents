"""Check that the reader-facing pages do not drift into talking about the build.

The pages under ``resources/`` and the two landing pages are read by people
who want to find a paper, a corpus, or a checklist. A line about how the
repository is generated, which script validates what, or how CI is wired is
addressed to whoever maintains the repository, not to whoever reads it, and it
breaks the voice of the page it sits in.

``CONTRIBUTING.md`` is where that material belongs, because the audience there
is people changing the repository. This check keeps the two audiences apart.

Run in CI:

    python scripts/check_voice.py
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Pages a reader arrives on. These carry the repository's voice, so they must
# talk about the field rather than about the repository's own plumbing.
READER_FACING = [
    "README.md",
    "resources/README.md",
    "resources/papers.md",
    "resources/corpora.md",
    "resources/by-area/README.md",
    "playbooks/README.md",
    "playbooks/evaluation-protocol.md",
    "playbooks/closed-loop-design.md",
    "playbooks/maturity-ladder.md",
]

# The one page whose audience is the people who change the repository. The
# tooling commentary belongs there, and this check makes sure it did not get
# deleted along with the copies on the reader-facing pages.
CONTRIBUTOR_FACING = ["CONTRIBUTING.md"]

# Phrases that belong on the contributor-facing page and nowhere else. Each
# entry is (pattern, what it is). The patterns are written to match the
# repository's own machinery rather than the general idea, so that ordinary
# prose about the field is never caught by accident.
BANNED = [
    (re.compile(r"\bscripts?/"), "a path into the scripts directory"),
    (re.compile(r"\b[\w-]+\.py\b"), "the name of a script"),
    (re.compile(r"^\s*python\s+\S", re.MULTILINE), "a command to run"),
    (re.compile(r"\bin CI\b|\bCI (runs|job|jobs|workflow|pipeline|fails)\b",
                re.IGNORECASE), "the build pipeline"),
    (re.compile(r"\bfails? the build\b", re.IGNORECASE), "the build pipeline"),
    (re.compile(r"\bdo not edit\b", re.IGNORECASE), "an editing instruction"),
    (re.compile(r"\bhand[- ]written\b", re.IGNORECASE), "how a file was produced"),
    (re.compile(r"\bgenerated by\b", re.IGNORECASE), "how a file was produced"),
    (re.compile(r"\bthe generator\b|\bgenerator script\b", re.IGNORECASE),
     "how a file was produced"),
    (re.compile(r"\bregenerat(?:e|es|ed|ing|ion)\b", re.IGNORECASE),
     "how a file was produced"),
    (re.compile(r"\bnot public\b", re.IGNORECASE), "the private source"),
    # The figures come from the survey, which is not published yet, so there
    # is nothing here to offer a reader for reuse. The pages must not imply
    # otherwise, and must not link the figure directory as a set to download.
    (re.compile(r"\b(?:re-?use|re-?using|borrowing)\b[^.\n]{0,40}"
                r"\b(?:figures?|images?|artwork|diagrams?)\b", re.IGNORECASE),
     "an offer to reuse the figures"),
    (re.compile(r"\b(?:figures?|images?|artwork|diagrams?)\b[^.\n]{0,40}"
                r"\b(?:re-?used|borrowed|redistributed)\b", re.IGNORECASE),
     "an offer to reuse the figures"),
    (re.compile(r"\]\([^)]*assets/figures\)"), "a link to the figure directory"),
]


def reader_pages() -> list[str]:
    pages = list(READER_FACING)
    pages += sorted("resources/by-area/" + p.name
                    for p in (ROOT / "resources" / "by-area").glob("*.md")
                    if p.name != "README.md")
    return pages


def main() -> int:
    problems = []
    pages = reader_pages()

    for name in pages:
        path = ROOT / name
        if not path.exists():
            problems.append("%s: missing page" % name)
            continue
        text = path.read_text(encoding="utf-8")

        for pattern, what in BANNED:
            for match in pattern.finditer(text):
                line = text[:match.start()].count("\n") + 1
                problems.append("%s:%d mentions %s (%r)"
                                % (name, line, what, match.group(0).strip()))

    # The material removed from the reader-facing pages has to live on the
    # contributor-facing page, or it is simply lost.
    for name in CONTRIBUTOR_FACING:
        path = ROOT / name
        if not path.exists():
            problems.append("%s: missing page" % name)
            continue
        text = path.read_text(encoding="utf-8")
        for needed in ("scripts/", "CI"):
            if needed not in text:
                problems.append("%s no longer explains %s" % (name, needed))

    for problem in problems:
        print("VOICE %s" % problem)
    print("\nchecked %d reader-facing pages | voice problems: %d"
          % (len(pages), len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
